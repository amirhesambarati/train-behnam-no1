#define SENSOR_MIN_CURRENT_MA 4.0f
#define SENSOR_MAX_CURRENT_MA 20.0f
#define PRESSURE_MIN_BAR      0.0f
#define PRESSURE_MAX_BAR      16.0f
void ReadAndPrintSensor(void)
{
    uint32_t adc_value;
    float voltage;
    float current_mA;
    float pressure_bar;

    adc_value = ADC_Read_PB1();

    // ????? ????? ADC ?? ?????
    voltage = ((float)adc_value * ADC_REFERENCE_V) / ADC_MAX_VALUE;

    // ????? ????? ?? ?? ?????? 100 ??? ?? ?????
    current_mA = (voltage / SHUNT_RESISTANCE_OHM) * 1000.0f;

    // ????? ???? ?? 4 ????????? ???? ???? ?? ???? ?????
    if (current_mA < SENSOR_MIN_CURRENT_MA)
    {
        printf("ADC: %lu | V: %.3f V | I: %.2f mA | Sensor disconnected\r\n",
               (unsigned long)adc_value,
               voltage,
               current_mA);
    }
    else
    {
        // ????????? ????? ???? ??????? ?? ???? ???? ?? ????? ?? ??????
        if (current_mA > SENSOR_MAX_CURRENT_MA)
        {
            current_mA = SENSOR_MAX_CURRENT_MA;
        }

        // ????? ??? 4 ?? 20 ????????? ?? 0 ?? 16 ???
        pressure_bar = ((current_mA - SENSOR_MIN_CURRENT_MA) /
                        (SENSOR_MAX_CURRENT_MA - SENSOR_MIN_CURRENT_MA)) *
                       (PRESSURE_MAX_BAR - PRESSURE_MIN_BAR);

        printf("ADC: %lu | V: %.3f V | I: %.2f mA | Pressure: %.2f bar\r\n",
               (unsigned long)adc_value,
               voltage,
               current_mA,
               pressure_bar);
    }
}
